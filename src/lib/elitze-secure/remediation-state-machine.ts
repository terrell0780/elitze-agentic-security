const STATE_SET = new Set<RemediationState>(REMEDIATION_STATES);
const EVENT_SET = new Set<RemediationEvent>(REMEDIATION_EVENTS);

export interface RemediationTransition {
  transitionId: string;
  previousState: RemediationState;
  state: RemediationState;
  event: RemediationEvent;
  allowed: boolean;
  reason: string;
}
export interface RemediationRecord {
  remediationId: string;
  tenantId: string;
  findingId: string;
  assetId?: string;
  state: RemediationState;
  version: number;
  createdAt: string;
  updatedAt: string;
}
export function isRemediationState(value: unknown): value is RemediationState { return typeof value === "string" && STATE_SET.has(value as RemediationState); }
export function isRemediationEvent(value: unknown): value is RemediationEvent { return typeof value === "string" && EVENT_SET.has(value as RemediationEvent); }

export function transitionRemediation(currentState: RemediationState, event: RemediationEvent): RemediationTransition {
  const target = TRANSITIONS.get(currentState)?.get(event);
  if (!target) return { transitionId: randomUUID(), previousState: currentState, state: currentState, event, allowed: false, reason: "No canonical transition from " + currentState + " on " + event };
  if (!STATE_SET.has(target)) throw new Error("remediation_transition_target_not_canonical:" + target);
  return { transitionId: randomUUID(), previousState: currentState, state: target, event, allowed: true, reason: event + ": " + currentState + " -> " + target };
}

export function createRemediationRecord(input: { remediationId?: string; tenantId: string; findingId: string; assetId?: string; now?: string }): RemediationRecord {
  const tenantId = input.tenantId.trim();
  const findingId = input.findingId.trim();
  if (!tenantId) throw new Error("tenant_id_required_for_remediation");
  if (!findingId) throw new Error("finding_id_required_for_remediation");
  const now = input.now ?? new Date().toISOString();
  return { remediationId: input.remediationId ?? randomUUID(), tenantId, findingId, assetId: input.assetId?.trim() || undefined, state: "DETECTED", version: 1, createdAt: now, updatedAt: now };
}

export function applyRemediationEvent(record: RemediationRecord, event: RemediationEvent, now = new Date().toISOString()): { record: RemediationRecord; transition: RemediationTransition } {
  const transition = transitionRemediation(record.state, event);
  if (!transition.allowed) return { record, transition };
  return { transition, record: { ...record, state: transition.state, version: record.version + 1, updatedAt: now } };
}

export function canonicalStateList(): readonly RemediationState[] { return REMEDIATION_STATES; }
export function canonicalTransitionTargets(): Record<RemediationState, readonly RemediationState[]> {
  return Object.fromEntries(REMEDIATION_STATES.map((state) => [state, [...new Set(TRANSITIONS.get(state)?.values() ?? [])]])) as Record<RemediationState, readonly RemediationState[]>;
}